#!/usr/bin/env node
/**
 * Text-targeted subset of every webfont we ship.
 *
 * Each face is narrowed to the EXACT glyph set its CSS selectors
 * render on the page (sourced from `scripts/lib/font-text-constants.js`,
 * cross-checked against `index.html` by
 * `tests/unit/font-subset-coverage.test.js`). The on-the-wire size
 * of every font drops to 4-10 KB vs ~14-25 KB for a generic
 * Latin-Extended-A subset.
 *
 * NOTE: an earlier `scripts/subset-fonts.js` (Latin-Ext-A subset
 * pipeline) was deleted because running it OVERWROTE the
 * text-targeted woff2 with the bigger Latin-Ext-A subset, silently
 * regressing every page-load. The text-targeted approach in this
 * script is the single canonical pipeline now.
 *
 * Per face:
 *   - cinzel-600.woff2            — nav links (above-fold, critical)
 *   - cinzel-700.woff2            — section h2 / h3, .section strong,
 *                                    footer strong, nav-active state,
 *                                    AND every LCP-region string (so
 *                                    the `'Cinzel LCP', cinzel, serif`
 *                                    fallback chain remains coherent
 *                                    if Cinzel LCP misses the
 *                                    font-display: optional window).
 *   - crimson-text-400-italic.woff2 — .hero-tagline (desktop) +
 *                                    .quote-liberty
 *
 * The Cinzel-700 LCP subset (`cinzel-700-lcp.woff2`) is generated by
 * `scripts/subset-fonts-lcp.js` — see that file for the LCP-only
 * argument. This script does NOT regenerate it.
 *
 * IMPORTANT: when adding visible text to a styled element, append
 * the literal string to the matching constant below AND re-run
 * `npm run build:fonts:page`. A character missing from the subset
 * will render in the @font-face fallback (system serif) for that one
 * glyph — usually obvious as a sudden shape mismatch.
 *
 * Usage: npm run build:fonts:page
 */

import { existsSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { default as subsetFont } from 'subset-font';

import {
  BODY_TEXT,
  HERO_TEXT,
  ITALIC_TEXT,
  NAV_TEXT,
  SECTION_HEADINGS_TEXT,
} from './lib/font-text-constants.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const FONTS_DIR = path.join(__dirname, '..', 'fonts');

/* Build the text envelope that must be passed to subset-font: the raw
   string plus its lowercased + uppercased variants, deduped via a Set.
   Each constant is a literal source-DOM string (matched by
   `tests/unit/font-subset-coverage.test.js` against the rendered DOM)
   — but `text-transform: uppercase` is applied BEFORE shaping, so the
   browser asks the font for uppercase glyphs even when source is
   lowercase. Including both cases is a sub-100-byte overhead per
   subset and prevents a single missing glyph from rendering in the
   fallback serif. */
function envelope(...sources) {
  const chars = new Set();
  for (const s of sources) {
    for (const ch of s) {
      chars.add(ch);
    }
    for (const ch of s.toLowerCase()) {
      chars.add(ch);
    }
    for (const ch of s.toUpperCase()) {
      chars.add(ch);
    }
  }
  return [...chars].join('');
}

const TARGETS = [
  {
    name: 'cinzel-400',
    /* Body paragraphs (.section p + footer p) inherit body's
       font-weight 400. Without this face declared, body weight 400
       fuzzy-matches to Cinzel-600 (NAV-only subset), producing
       per-glyph fallback for any char outside NAV — visible
       "macedonia" rendering. cinzel-400 covers EVERY char any body
       paragraph or footer paragraph renders. We also envelope
       NAV_TEXT + HERO_TEXT + SECTION_HEADINGS_TEXT + ITALIC_TEXT
       defensively so weight-400 text in any selector that doesn't
       target Cinzel-LCP/600/700/Crimson explicitly still renders
       correctly. */
    text: envelope(BODY_TEXT, NAV_TEXT, HERO_TEXT, SECTION_HEADINGS_TEXT, ITALIC_TEXT),
  },
  {
    name: 'cinzel-600',
    text: envelope(NAV_TEXT),
    /* Nav-active state actually uses Cinzel-700, not 600 — see
       4-header.css `nav a` (weight 600) vs `@keyframes
       nav-active-section` (weight 700). So Cinzel-600 only needs nav
       glyphs at base state. */
  },
  {
    name: 'cinzel-700',
    text: envelope(NAV_TEXT, HERO_TEXT, SECTION_HEADINGS_TEXT),
  },
  {
    name: 'crimson-text-400-italic',
    text: envelope(ITALIC_TEXT),
  },
];

let totalBefore = 0;
let totalAfter = 0;
const reports = [];

for (const { name, text } of TARGETS) {
  const ttfPath = path.join(FONTS_DIR, `${name}.ttf`);
  const woff2Path = path.join(FONTS_DIR, `${name}.woff2`);

  /* Prefer the .ttf source when present (lossless re-subset), but fall
     back to the existing .woff2 when no TTF is shipped (Crimson Text
     italic is woff2-only — sourced directly from Google Fonts in the
     compressed format, no TTF intermediate). subset-font accepts either
     input format and re-encodes as woff2. */
  let sourcePath;
  if (existsSync(ttfPath)) {
    sourcePath = ttfPath;
  } else if (existsSync(woff2Path)) {
    sourcePath = woff2Path;
  } else {
    console.error(`[ERROR] Source font missing for ${name}: tried ${ttfPath} and ${woff2Path}`);
    process.exit(1);
  }

  const sourceBuf = readFileSync(sourcePath);
  const subsetted = await subsetFont(sourceBuf, text, { targetFormat: 'woff2' });

  const before = statSync(woff2Path).size;
  writeFileSync(woff2Path, subsetted);
  const after = subsetted.length;
  totalBefore += before;
  totalAfter += after;

  const saved = before - after;
  const pct = before > 0 ? ((saved / before) * 100).toFixed(1) : '0.0';
  const uniqueGlyphs = new Set(text).size;
  reports.push(
    `${name}.woff2: ${(before / 1024).toFixed(1)} KB → ${(after / 1024).toFixed(1)} KB ` +
      `(saved ${(saved / 1024).toFixed(1)} KB, ${pct}%, ${uniqueGlyphs} unique chars)`,
  );
}

for (const line of reports) {
  console.log(line);
}
console.log(
  `\nTotal: ${(totalBefore / 1024).toFixed(1)} KB → ${(totalAfter / 1024).toFixed(1)} KB ` +
    `(saved ${((totalBefore - totalAfter) / 1024).toFixed(1)} KB, ` +
    `${(((totalBefore - totalAfter) / totalBefore) * 100).toFixed(1)}%)`,
);
